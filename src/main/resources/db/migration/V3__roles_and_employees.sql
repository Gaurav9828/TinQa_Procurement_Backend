-- Custom roles built from permission groups, employees and their profile change requests.
-- Tables: custom_role, custom_role_group, employee, employee_profile_change_request.

-- custom_role ---------------------------------------------------------------------------------------------------------

CREATE TABLE custom_role (
    id bigserial NOT NULL,
    code character varying(60) NOT NULL,
    label character varying(100) NOT NULL,
    department character varying(100) NOT NULL,
    description character varying(500),
    active boolean DEFAULT true NOT NULL,
    created_by bigint,
    created_at timestamp with time zone NOT NULL,
    updated_by bigint,
    updated_at timestamp with time zone NOT NULL,
    CONSTRAINT chk_custom_role_code CHECK (((code)::text ~ '^[A-Z][A-Z0-9_]{1,59}$'::text)),
    CONSTRAINT custom_role_pkey PRIMARY KEY (id),
    CONSTRAINT uk_custom_role_code UNIQUE (code),
    CONSTRAINT custom_role_created_by_fkey FOREIGN KEY (created_by) REFERENCES users(id),
    CONSTRAINT custom_role_updated_by_fkey FOREIGN KEY (updated_by) REFERENCES users(id)
);

-- custom_role_group ---------------------------------------------------------------------------------------------------

CREATE TABLE custom_role_group (
    role_id bigint NOT NULL,
    permission_group character varying(60) NOT NULL,
    CONSTRAINT chk_custom_role_group_allowed CHECK (((permission_group)::text <> ALL (ARRAY[('SUPPLIER_PORTAL'::character varying)::text, ('SYSTEM_ADMINISTRATION'::character varying)::text, ('SELF_SERVICE'::character varying)::text]))),
    CONSTRAINT custom_role_group_pkey PRIMARY KEY (role_id, permission_group),
    CONSTRAINT custom_role_group_role_id_fkey FOREIGN KEY (role_id) REFERENCES custom_role(id) ON DELETE CASCADE
);

-- employee ------------------------------------------------------------------------------------------------------------

CREATE TABLE employee (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint NOT NULL,
    employee_code character varying(50) NOT NULL,
    first_name character varying(100) NOT NULL,
    middle_name character varying(100),
    last_name character varying(100),
    display_name character varying(200) NOT NULL,
    date_of_birth date,
    gender character varying(20),
    designation character varying(100),
    department character varying(100),
    employment_type character varying(30) DEFAULT 'FULL_TIME'::character varying NOT NULL,
    joining_date date NOT NULL,
    leaving_date date,
    salary_amount numeric(15,2),
    salary_currency character varying(10) DEFAULT 'INR'::character varying,
    phone character varying(20) NOT NULL,
    alternate_phone character varying(20),
    personal_email character varying(150),
    status character varying(20) DEFAULT 'ACTIVE'::character varying NOT NULL,
    created_by bigint,
    approval_decided_by bigint,
    approval_decided_at timestamp without time zone,
    approval_rejection_reason character varying(500),
    created_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    pan_number character varying(10),
    house_number character varying(100),
    street character varying(500),
    landmark character varying(255),
    district character varying(100),
    state character varying(100),
    pincode character varying(10),
    google_maps_url text,
    deleted_by bigint,
    deleted_at timestamp without time zone,
    custom_role_id bigint,
    CONSTRAINT chk_employee_one_designation CHECK (((designation IS NULL) <> (custom_role_id IS NULL))),
    CONSTRAINT employee_pkey PRIMARY KEY (id),
    CONSTRAINT employee_employee_code_key UNIQUE (employee_code),
    CONSTRAINT employee_user_id_key UNIQUE (user_id),
    CONSTRAINT employee_approval_decided_by_fkey FOREIGN KEY (approval_decided_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT employee_created_by_fkey FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT employee_custom_role_id_fkey FOREIGN KEY (custom_role_id) REFERENCES custom_role(id),
    CONSTRAINT employee_deleted_by_fkey FOREIGN KEY (deleted_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT employee_user_id_fkey FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE INDEX idx_employee_custom_role ON employee USING btree (custom_role_id) WHERE (custom_role_id IS NOT NULL);
CREATE INDEX idx_employee_designation ON employee USING btree (designation) WHERE (designation IS NOT NULL);
CREATE INDEX idx_employee_display_name_trgm ON employee USING gin (lower((display_name)::text) gin_trgm_ops);
CREATE INDEX idx_employee_status_created ON employee USING btree (status, created_at, id);
CREATE UNIQUE INDEX uq_employee_pan_number ON employee USING btree (pan_number) WHERE (pan_number IS NOT NULL);
CREATE UNIQUE INDEX uq_employee_personal_email ON employee USING btree (lower((personal_email)::text)) WHERE (personal_email IS NOT NULL);
CREATE UNIQUE INDEX uq_employee_phone ON employee USING btree (phone);

-- employee_profile_change_request -------------------------------------------------------------------------------------

CREATE TABLE employee_profile_change_request (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    employee_id bigint NOT NULL,
    requested_by bigint NOT NULL,
    approved_by bigint,
    first_name character varying(100),
    middle_name character varying(100),
    last_name character varying(100),
    display_name character varying(200),
    date_of_birth date,
    gender character varying(20),
    department character varying(100),
    designation character varying(100),
    personal_email character varying(255),
    primary_phone character varying(20),
    alternate_phone character varying(20),
    status character varying(30) DEFAULT 'PENDING'::character varying NOT NULL,
    rejection_reason character varying(500),
    requested_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    reviewed_at timestamp without time zone,
    created_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT chk_profile_change_status CHECK ((status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED'))),
    CONSTRAINT employee_profile_change_request_pkey PRIMARY KEY (id),
    CONSTRAINT employee_profile_change_request_approved_by_fkey FOREIGN KEY (approved_by) REFERENCES users(id),
    CONSTRAINT employee_profile_change_request_employee_id_fkey FOREIGN KEY (employee_id) REFERENCES employee(id),
    CONSTRAINT employee_profile_change_request_requested_by_fkey FOREIGN KEY (requested_by) REFERENCES users(id)
);

CREATE INDEX idx_profile_change_employee_status ON employee_profile_change_request USING btree (employee_id, status);
CREATE INDEX idx_profile_change_requested_by ON employee_profile_change_request USING btree (requested_by);
CREATE INDEX idx_profile_change_status_requested ON employee_profile_change_request USING btree (status, requested_at DESC);
