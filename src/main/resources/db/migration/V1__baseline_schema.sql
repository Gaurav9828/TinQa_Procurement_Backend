CREATE INDEX idx_document_owner_id ON document (owner_id);
CREATE INDEX idx_document_status ON document (status);


-- ---------------------------------------------------------------------------------------------------------------------
-- Catalogue: categories, items, dealers
-- ---------------------------------------------------------------------------------------------------------------------

-- Shared by several modules; each works with its own type (ITEM, DEALER, ...)
CREATE TABLE categories
(
    id          BIGSERIAL PRIMARY KEY,
    type        VARCHAR(50)  NOT NULL,
    name        VARCHAR(100) NOT NULL,
    code        VARCHAR(50)  NOT NULL,
    description TEXT,
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    created_by  BIGINT,
    updated_by  BIGINT,
    -- Unique per category type (these also serve lookups by type)
    CONSTRAINT uq_categories_type_name UNIQUE (type, name),
    CONSTRAINT uq_categories_type_code UNIQUE (type, code)
);

CREATE TABLE items
(
    id                  BIGSERIAL PRIMARY KEY,
    category_id         BIGINT         NOT NULL REFERENCES categories (id),
    name                VARCHAR(255)   NOT NULL,
    brand               VARCHAR(100),
    sku                 VARCHAR(100)   NOT NULL UNIQUE,
    unit_of_measure     VARCHAR(50)    NOT NULL,
    mrp                 NUMERIC(12, 2) NOT NULL,
    country_of_origin   VARCHAR(50)    NOT NULL,
    raw_materials_used  TEXT,
    terms_and_condition TEXT,
    description         TEXT,
    attributes          JSONB,
    is_active           BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    created_by          BIGINT,
    updated_by          BIGINT
);

CREATE INDEX idx_items_category ON items (category_id);

-- An item can carry several warranties
CREATE TABLE item_warranties
(
    id                   BIGSERIAL PRIMARY KEY,
    item_id              BIGINT       NOT NULL REFERENCES items (id) ON DELETE CASCADE,
    warranty_type        VARCHAR(30)  NOT NULL, -- MANUFACTURER, SELLER, EXTENDED, REPLACEMENT, SERVICE, PARTS, LIMITED
    title                VARCHAR(255) NOT NULL,
    duration_value       INT          NOT NULL,
    duration_unit        VARCHAR(10)  NOT NULL, -- DAYS, MONTHS, YEARS
    provider             VARCHAR(255),          -- who honours the warranty (brand, manufacturer, dealer, ...)
    coverage             TEXT,
    exclusions           TEXT,
    terms_and_conditions TEXT,
    is_active            BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at           TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    created_by           BIGINT,
    updated_by           BIGINT,
    CONSTRAINT chk_item_warranties_duration_positive CHECK (duration_value > 0)
);

CREATE INDEX idx_item_warranties_item ON item_warranties (item_id);

CREATE TABLE dealers
(
    id                     BIGSERIAL PRIMARY KEY,
    name                   VARCHAR(255) NOT NULL,
    trade_name             VARCHAR(255),
    email                  VARCHAR(150) NOT NULL,
    phone_number           VARCHAR(20)  NOT NULL,
    alternate_phone_number VARCHAR(20),
    street                 TEXT         NOT NULL,
    landmark               VARCHAR(255),
    city                   VARCHAR(100) NOT NULL,
    district               VARCHAR(100),
    state                  VARCHAR(100) NOT NULL,
    country                VARCHAR(100) NOT NULL DEFAULT 'India',
    pincode                VARCHAR(20)  NOT NULL,
    google_maps_url        TEXT,
    gstin                  VARCHAR(15) UNIQUE,
    is_gst_verified        BOOLEAN      NOT NULL DEFAULT FALSE,
    pan_number             VARCHAR(10),
    business_since         INT,
    employee_count         INT,
    offers_shipping        BOOLEAN      NOT NULL DEFAULT FALSE,
    does_bulk_dealing      BOOLEAN      NOT NULL DEFAULT TRUE,
    does_wholesale_dealing BOOLEAN      NOT NULL DEFAULT TRUE,
    is_active              BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at             TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at             TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    created_by             BIGINT,
    updated_by             BIGINT
);

CREATE TABLE dealer_category_mappings
(
    dealer_id   BIGINT NOT NULL REFERENCES dealers (id) ON DELETE CASCADE,
    category_id BIGINT NOT NULL REFERENCES categories (id) ON DELETE CASCADE,
    PRIMARY KEY (dealer_id, category_id)
);

CREATE INDEX idx_dealer_category_mappings_category ON dealer_category_mappings (category_id);


-- ---------------------------------------------------------------------------------------------------------------------
-- Orders
-- ---------------------------------------------------------------------------------------------------------------------

-- Forward-only workflow: new orders start as a quotation; returns and refunds follow delivery
CREATE TABLE orders
(
    id                BIGSERIAL PRIMARY KEY,
    order_number      VARCHAR(50)    NOT NULL UNIQUE,
    dealer_id         BIGINT         NOT NULL REFERENCES dealers (id),
    item_id           BIGINT         NOT NULL REFERENCES items (id),
    order_quantity    NUMERIC(14, 3) NOT NULL,
    unit_type         VARCHAR(20)    NOT NULL,
    unit_price        NUMERIC(12, 2) NOT NULL,
    total_price       NUMERIC(14, 2) NOT NULL,
    shipment_price    NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    tax_breakup       JSONB          NOT NULL DEFAULT '{}'::jsonb,
    order_status      VARCHAR(30)    NOT NULL DEFAULT 'QUOTATION',
    expected_delivery DATE,
    actual_delivery   DATE,
    order_date        DATE           NOT NULL,
    additional_info   JSONB          NOT NULL DEFAULT '{}'::jsonb,
    created_at        TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    created_by        BIGINT         NOT NULL REFERENCES users (id),
    updated_by        BIGINT REFERENCES users (id),
    CONSTRAINT chk_orders_status CHECK (order_status IN (
        'QUOTATION', 'PENDING', 'DEALER_LEVEL_PENDING', 'CONFIRMED', 'SHIPPED', 'DELIVERED', 'CANCELLED',
        'RETURN_REQUESTED', 'RETURN_APPROVED', 'RETURN_REJECTED', 'RETURN_PICKED_UP', 'RETURN_RECEIVED',
        'REFUND_INITIATED', 'REFUND_FAILED', 'REFUND_COMPLETED'))
);

CREATE INDEX idx_orders_dealer ON orders (dealer_id);
CREATE INDEX idx_orders_item ON orders (item_id);
CREATE INDEX idx_orders_status ON orders (order_status);

-- Append-only: one row per status change (from_status is null for the row written at creation)
CREATE TABLE order_status_history
(
    id              BIGSERIAL PRIMARY KEY,
    order_id        BIGINT                   NOT NULL REFERENCES orders (id),
    from_status     VARCHAR(30),
    to_status       VARCHAR(30)              NOT NULL,
    changed_by      BIGINT                   NOT NULL REFERENCES users (id),
    reason          VARCHAR(500),
    actual_delivery DATE,
    changed_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_order_status_history_order ON order_status_history (order_id, changed_at);


-- ---------------------------------------------------------------------------------------------------------------------
-- Stock
-- ---------------------------------------------------------------------------------------------------------------------

-- Goods received from a delivered order, approved by Admin L2. One order is received into exactly one entry
-- (unique order_number), so concurrent requests cannot record its quantity twice.
CREATE TABLE stock
(
    id                    BIGSERIAL PRIMARY KEY,
    stock_identity_number VARCHAR(100)   NOT NULL UNIQUE,
    batch_number          VARCHAR(100)   NOT NULL,
    order_number          VARCHAR(50)    NOT NULL UNIQUE REFERENCES orders (order_number),
    dealer_id             BIGINT         NOT NULL REFERENCES dealers (id),
    item_id               BIGINT         NOT NULL REFERENCES items (id),
    units_passed_test     NUMERIC(14, 3) NOT NULL DEFAULT 0.000,
    defected_units        NUMERIC(14, 3) NOT NULL DEFAULT 0.000,
    available_units       NUMERIC(14, 3) NOT NULL DEFAULT 0.000,
    has_tested            BOOLEAN        NOT NULL DEFAULT FALSE,
    additional_info       JSONB          NOT NULL DEFAULT '{}'::jsonb,
    approval_status       VARCHAR(30)    NOT NULL DEFAULT 'PENDING',
    approved_by           BIGINT REFERENCES users (id),
    approved_at           TIMESTAMP WITH TIME ZONE,
    rejection_reason      VARCHAR(500),
    date_of_arrival       DATE           NOT NULL,
    is_active             BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at            TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    created_by            BIGINT         NOT NULL REFERENCES users (id),
    updated_by            BIGINT REFERENCES users (id)
);

CREATE INDEX idx_stock_item ON stock (item_id);
CREATE INDEX idx_stock_dealer ON stock (dealer_id);
CREATE INDEX idx_stock_approval_status ON stock (approval_status);

-- Item stock movements requested by other services (e.g. Ecommerce products built from items).
-- One row per movement_id (idempotency key); allocations record exactly which stock entries moved.
CREATE TABLE item_stock_movements
(
    id           BIGSERIAL PRIMARY KEY,
    movement_id  UUID         NOT NULL UNIQUE,
    source       VARCHAR(50)  NOT NULL, -- e.g. ECOMMERCE_PRODUCT
    reference    VARCHAR(100) NOT NULL, -- e.g. product:42; returns only draw on what this reference consumed
    status       VARCHAR(20)  NOT NULL, -- APPLIED, REVERSED
    performed_by VARCHAR(255),
    created_at   TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    reversed_at  TIMESTAMP WITH TIME ZONE,
    reversed_by  VARCHAR(255)
);

CREATE INDEX idx_item_stock_movements_source_reference ON item_stock_movements (source, reference);

CREATE TABLE item_stock_movement_allocations
(
    id          BIGSERIAL PRIMARY KEY,
    movement_id BIGINT         NOT NULL REFERENCES item_stock_movements (id) ON DELETE CASCADE,
    line_index  INT            NOT NULL,
    item_id     BIGINT         NOT NULL REFERENCES items (id),
    stock_id    BIGINT         NOT NULL REFERENCES stock (id),
    units       NUMERIC(14, 3) NOT NULL, -- positive = consumed from the stock entry, negative = returned to it
    created_at  TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_item_stock_movement_allocations_units_non_zero CHECK (units <> 0)
);

CREATE INDEX idx_item_stock_movement_allocations_movement ON item_stock_movement_allocations (movement_id);
CREATE INDEX idx_item_stock_movement_allocations_item_stock ON item_stock_movement_allocations (item_id, stock_id);


-- ---------------------------------------------------------------------------------------------------------------------
-- Products
-- ---------------------------------------------------------------------------------------------------------------------

-- Each product is an instance of a configured item and consumes `quantity` of it
CREATE TABLE products
(
    id         BIGSERIAL PRIMARY KEY,
    product_id VARCHAR(50)    NOT NULL UNIQUE, -- business identifier, e.g. PRD-1728375000000-AB12
    item_id    BIGINT         NOT NULL REFERENCES items (id),
    quantity   NUMERIC(14, 3) NOT NULL,
    is_active  BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT,
    updated_by BIGINT,
    CONSTRAINT chk_products_quantity_positive CHECK (quantity > 0)
);

CREATE INDEX idx_products_item ON products (item_id);
CREATE INDEX idx_products_is_active ON products (is_active);

-- Which stock entries a product's quantity was taken from (FIFO by arrival), to return it if the product is deleted
CREATE TABLE product_stock_allocations
(
    id         BIGSERIAL PRIMARY KEY,
    product_id BIGINT         NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    stock_id   BIGINT         NOT NULL REFERENCES stock (id),
    quantity   NUMERIC(14, 3) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT,
    CONSTRAINT chk_product_stock_allocations_quantity_positive CHECK (quantity > 0)
);

CREATE INDEX idx_product_stock_allocations_product ON product_stock_allocations (product_id);
CREATE INDEX idx_product_stock_allocations_stock ON product_stock_allocations (stock_id);


-- ---------------------------------------------------------------------------------------------------------------------
-- Product approvals (Admin L2 approval of products that live in the Ecommerce service, so no FK to them)
-- ---------------------------------------------------------------------------------------------------------------------

CREATE TABLE product_approval_requests
(
    id                   BIGSERIAL PRIMARY KEY,
    ecommerce_product_id BIGINT                   NOT NULL,
    product_title        VARCHAR(150)             NOT NULL,
    request_type         VARCHAR(20)              NOT NULL, -- CREATE, RESUBMISSION, UPDATE
    status               VARCHAR(20)              NOT NULL, -- PENDING, APPROVED, REJECTED, CANCELLED
    snapshot             JSONB                    NOT NULL, -- what the reviewer saw
    requested_by         BIGINT                   NOT NULL REFERENCES users (id),
    requested_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    decided_by           BIGINT REFERENCES users (id),
    decided_at           TIMESTAMP WITH TIME ZONE,
    decision_reason      VARCHAR(500),
    -- UPDATE requests only
    proposed_changes     JSONB,                             -- full Ecommerce PUT body to apply once approved (opaque here)
    previous_snapshot    JSONB,                             -- live product when the change was requested
    change_summary       JSONB,                             -- [{label, oldValue, newValue}] for the reviewer
    applied_at           TIMESTAMP WITH TIME ZONE,          -- when the approved change was written to Ecommerce
    applied_by           BIGINT REFERENCES users (id) ON DELETE SET NULL,
    version              BIGINT                   NOT NULL DEFAULT 0,

    CONSTRAINT chk_product_approval_requests_type CHECK (request_type IN ('CREATE', 'RESUBMISSION', 'UPDATE')),
    CONSTRAINT chk_product_approval_requests_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT chk_product_approval_requests_reason CHECK (
        status NOT IN ('REJECTED', 'CANCELLED') OR btrim(coalesce(decision_reason, '')) <> ''),
    CONSTRAINT chk_product_approval_requests_update_fields CHECK (
        request_type <> 'UPDATE'
            OR (jsonb_typeof(proposed_changes) = 'object' AND previous_snapshot IS NOT NULL
                AND jsonb_typeof(change_summary) = 'array')),
    -- Changes are only approved or rejected, never cancelled, and only approved changes can be applied
    CONSTRAINT chk_product_approval_requests_update_status CHECK (request_type <> 'UPDATE' OR status <> 'CANCELLED'),
    CONSTRAINT chk_product_approval_requests_applied CHECK (
        applied_at IS NULL OR (request_type = 'UPDATE' AND status = 'APPROVED'))
);

CREATE INDEX idx_product_approval_requests_product_requested
    ON product_approval_requests (ecommerce_product_id, requested_at DESC);
CREATE INDEX idx_product_approval_requests_status ON product_approval_requests (status);

-- At most one request per product can be waiting for a decision
CREATE UNIQUE INDEX uq_product_approval_requests_one_pending
    ON product_approval_requests (ecommerce_product_id) WHERE status = 'PENDING';
