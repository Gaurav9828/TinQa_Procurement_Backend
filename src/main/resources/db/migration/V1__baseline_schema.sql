-- =====================================================================================================================
-- TinQa Procurement: baseline schema
--
-- The complete schema in one migration. It replaces the original V1-V20 history, so databases created from that
-- history must be recreated. Every later change goes into a new V2+ migration; never edit this file once applied.
--
-- Sections: security, employees, notifications, documents, catalogue (categories, items, dealers),
--           orders, stock, products, product approvals
-- =====================================================================================================================


-- ---------------------------------------------------------------------------------------------------------------------
-- Security
-- ---------------------------------------------------------------------------------------------------------------------

CREATE TABLE users
(
    id                  BIGSERIAL PRIMARY KEY,
    username            VARCHAR(100) NOT NULL UNIQUE,
    email               VARCHAR(150) NOT NULL UNIQUE,
    password            VARCHAR(255) NOT NULL,
    role                VARCHAR(20)  NOT NULL,
    auth_client         VARCHAR(20)  NOT NULL,
    enabled             BOOLEAN      NOT NULL DEFAULT TRUE,
    account_non_locked  BOOLEAN      NOT NULL DEFAULT TRUE,
    is_first_login      BOOLEAN      NOT NULL DEFAULT TRUE,
    -- Tokens issued before this moment are rejected, so setting a password signs out every session
    password_changed_at TIMESTAMP WITH TIME ZONE,
    created_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP
);

-- Usernames and emails are unique regardless of letter case
CREATE UNIQUE INDEX uq_users_username_lower ON users (lower(username));
CREATE UNIQUE INDEX uq_users_email_lower ON users (lower(email));
CREATE INDEX idx_users_role ON users (role);

-- Security events on login accounts. Never holds a password or its hash.
CREATE TABLE auth_audit_events
(
    id          BIGSERIAL PRIMARY KEY,
    user_id     BIGINT                   REFERENCES users (id) ON DELETE SET NULL,
    username    VARCHAR(100)             NOT NULL,
    event_type  VARCHAR(50)              NOT NULL,
    ip_address  VARCHAR(64),
    user_agent  VARCHAR(512),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_auth_audit_events_user_id ON auth_audit_events (user_id);
CREATE INDEX idx_auth_audit_events_occurred_at ON auth_audit_events (occurred_at);


-- ---------------------------------------------------------------------------------------------------------------------
-- Employees
-- ---------------------------------------------------------------------------------------------------------------------

CREATE TABLE employee
(
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                   BIGINT       NOT NULL UNIQUE REFERENCES users (id),
    employee_code             VARCHAR(50)  NOT NULL UNIQUE,
    first_name                VARCHAR(100) NOT NULL,
    middle_name               VARCHAR(100),
    last_name                 VARCHAR(100),
    display_name              VARCHAR(200) NOT NULL,
    date_of_birth             DATE,
    gender                    VARCHAR(20),
    designation               VARCHAR(100) NOT NULL,
    department                VARCHAR(100),
    employment_type           VARCHAR(30)  NOT NULL DEFAULT 'FULL_TIME',
    joining_date              DATE         NOT NULL,
    leaving_date              DATE,
    salary_amount             DECIMAL(15, 2),
    salary_currency           VARCHAR(10)           DEFAULT 'INR',
    phone                     VARCHAR(20)  NOT NULL,
    alternate_phone           VARCHAR(20),
    personal_email            VARCHAR(150),
    status                    VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    -- Who created the employee, and the Admin L2 decision on employees that need approval
    created_by                BIGINT REFERENCES users (id) ON DELETE SET NULL,
    approval_decided_by       BIGINT REFERENCES users (id) ON DELETE SET NULL,
    approval_decided_at       TIMESTAMP,
    approval_rejection_reason VARCHAR(500),
    created_at                TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Contact details identify one person (the service also checks alternate phones and other spellings of a number)
CREATE UNIQUE INDEX uq_employee_phone ON employee (phone);
CREATE UNIQUE INDEX uq_employee_personal_email ON employee (lower(personal_email)) WHERE personal_email IS NOT NULL;
CREATE INDEX idx_employee_status ON employee (status);

-- Admin L1 profile changes that wait for Admin L2. Only the requested approval-controlled fields are filled in.
CREATE TABLE employee_profile_change_request
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id      BIGINT       NOT NULL REFERENCES employee (id),
    requested_by     BIGINT       NOT NULL REFERENCES users (id),
    approved_by      BIGINT REFERENCES users (id),
    first_name       VARCHAR(100),
    middle_name      VARCHAR(100),
    last_name        VARCHAR(100),
    display_name     VARCHAR(200),
    date_of_birth    DATE,
    gender           VARCHAR(20),
    department       VARCHAR(100),
    designation      VARCHAR(100),
    personal_email   VARCHAR(255),
    primary_phone    VARCHAR(20),
    alternate_phone  VARCHAR(20),
    status           VARCHAR(30)  NOT NULL DEFAULT 'PENDING',
    rejection_reason VARCHAR(500),
    requested_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at      TIMESTAMP,
    created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_profile_change_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED'))
);

CREATE INDEX idx_profile_change_employee_status ON employee_profile_change_request (employee_id, status);
CREATE INDEX idx_profile_change_status ON employee_profile_change_request (status);
CREATE INDEX idx_profile_change_requested_by ON employee_profile_change_request (requested_by);


-- ---------------------------------------------------------------------------------------------------------------------
-- Notifications
-- ---------------------------------------------------------------------------------------------------------------------

CREATE TABLE notification
(
    id         BIGSERIAL PRIMARY KEY,
    title      VARCHAR(150) NOT NULL,
    message    TEXT         NOT NULL,
    broadcast  BOOLEAN      NOT NULL DEFAULT FALSE,
    created_by BIGINT REFERENCES users (id),
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- A notification without text carries no information
    CONSTRAINT chk_notification_title_not_blank CHECK (btrim(title) <> ''),
    CONSTRAINT chk_notification_message_not_blank CHECK (btrim(message) <> '')
);

CREATE INDEX idx_notification_created_at ON notification (created_at);

CREATE TABLE notification_recipient
(
    id              BIGSERIAL PRIMARY KEY,
    notification_id BIGINT    NOT NULL REFERENCES notification (id) ON DELETE CASCADE,
    user_id         BIGINT    NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    read            BOOLEAN   NOT NULL DEFAULT FALSE,
    read_at         TIMESTAMP,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_notification_recipient UNIQUE (notification_id, user_id)
);

CREATE INDEX idx_notification_recipient_user_read ON notification_recipient (user_id, read);


